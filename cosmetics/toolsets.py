"""Tool skin sets (catalog v1.2): 12 themed sets x 19 textures of 16x16, all drawn here from scratch.

Every set has 10 templates (sword, pickaxe, axe, shovel, hoe, rod, bow, crossbow, and check.NEW_STATES: paxel, one
hammer that every Just Hammers kind shares); the 19 textures come from them: the rod with and without its line, the
bow with its string and arrow in 4 draw states, the crossbow with its string in 4 states plus a loaded arrow and a
loaded firework rocket. One design per tool type serves all its material tiers.

A template is 16 strings of 16 characters (handle bottom-left, working end top-right, as vanilla):
  '.'          transparent
  '#'          head material, auto-shaded with the head ramp '1' (darkest) .. '5' (highlight)
  '%'          trim material (guards, collars, rims), auto-shaded with the trim ramp 'p' (dark) .. 's' (light)
  '1'..'5'     head ramp, placed by hand (facets, cracks, highlights); counts as head material for the shading
  'p'..'s'     trim ramp by hand; counts as trim material
  'H'          handle, shaded as a lit / mid / shadow cylinder and patterned with the set's grip (wrap bands etc.)
  '@'          string / line anchor (bow limb tips, crossbow prod tips, rod tip), drawn in the string colour
  any other    an inlay colour of the set palette (gems 'x' 'y' 'z', glow, sparkle, cracks, stripes); inlays sit inside
               a material without making an edge
Palette keys used by the code: 'u' 'v' 'w' handle dark / mid / light, 'U' 'V' 'W' the same for the grip pattern,
'S' string and fishing line, 'A' 'a' arrowhead tip / barbs, 'B' arrow shaft, 'F' 'f' fletching (and the crossbow
bolt's shaft), 'R' 'r' 'O' 'Q' the firework rocket (defaults below); the fishing lure takes the gem colours.
Auto-shading lights every pixel from the top-left: a pixel's outward normal is the sum of the directions to its
neighbours outside its material; edges facing the light take the light tones, edges facing away the darkest, the
interior the mid tone. Nothing is random, so the same template always gives the same bytes.
"""
import math

from PIL import Image

from cosmetics.art import hexrgb
from cosmetics.check import NEW_STATES

HEAD, TRIM = '12345', 'pqrs'
LIGHT = (-1 / math.sqrt(2), -1 / math.sqrt(2))  # toward the top-left
NEIGHBOURS = [(dx, dy, 1.0 if dx == 0 or dy == 0 else 0.7) for dx in (-1, 0, 1) for dy in (-1, 0, 1) if dx or dy]


def material(ch):
    if ch in '#' + HEAD:
        return 'head'
    if ch in '%' + TRIM:
        return 'trim'
    if ch == 'H':
        return 'handle'
    return 'empty' if ch == '.' else 'inlay'


def _open(grid, x, y, mat):
    """Does the pixel at (x, y) bound a pixel of material mat? Inlays (gems, sparkles, cracks) sit inside a material
    without making an edge; transparency and the other base materials do."""
    if not (0 <= x < 16 and 0 <= y < 16):
        return True
    other = material(grid[y][x])
    return other != mat and other != 'inlay'


def _steps(grid, x, y, mat, d):
    """Diagonal steps from (x, y) toward the top-left (d = -1) or bottom-right (d = 1) until leaving the material."""
    n = 0
    while not _open(grid, x, y, mat):
        x, y, n = x + d, y + d, n + 1
    return n


def _tone(grid, x, y):
    """Head-ramp tone 1..5 of an auto-shaded pixel from its exposure to pixels outside its material."""
    mat = material(grid[y][x])
    ox = oy = dx_ = dy_ = 0.0
    orth = exposed = 0
    for dx, dy, w in NEIGHBOURS:
        if _open(grid, x + dx, y + dy, mat):
            exposed += 1
            if w == 1.0:
                ox, oy, orth = ox + dx, oy + dy, orth + 1
            else:
                dx_, dy_ = dx_ + dx, dy_ + dy
    if orth:
        nx, ny = ox + 0.5 * dx_, oy + 0.5 * dy_
    else:
        nx, ny = dx_, dy_
    length = math.hypot(nx, ny)
    if length < 0.5:
        if exposed:
            return 3  # a thin strip open on opposite sides
        # interior: a cylinder-like gradient from the steps to the edge toward the light and away from it
        lit_steps = _steps(grid, x, y, mat, -1)
        dark_steps = _steps(grid, x, y, mat, 1)
        f = lit_steps / (lit_steps + dark_steps)
        return 4 if f < 0.34 else 2 if f > 0.75 else 3
    lit = (nx * LIGHT[0] + ny * LIGHT[1]) / length
    if not orth:  # one pixel in from a diagonal edge
        return 4 if lit > 0.4 else 2 if lit < -0.4 else 3
    if lit > 0.9 and orth >= 2:
        return 5  # a corner facing the light
    if lit > 0.4:
        return 4
    if lit > -0.2:
        return 3
    if lit > -0.6:
        return 2
    return 1


TRIM_TONE = {1: 'p', 2: 'q', 3: 'q', 4: 'r', 5: 's'}


GRIPS = {  # pattern along the handle: t = x - y grows toward the head, s = x + y across it -> use the wrap ramp?
    'plain': lambda t, s: False,
    'bands': lambda t, s: t % 4 == 0,
    'spiral': lambda t, s: (t + s) % 5 == 0,
    'hazard': lambda t, s: (t // 2) % 2 == 0,
    'double': lambda t, s: t % 6 in (0, 1),
}


def _handle(grid, x, y, grip):
    """Lit / mid / shadow from which sides the pixel is open on, then the grip pattern picks plain or wrap colours."""
    def open_(xx, yy):
        return not (0 <= xx < 16 and 0 <= yy < 16) or grid[yy][xx] != 'H'
    ul = open_(x - 1, y) + open_(x, y - 1)
    dr = open_(x + 1, y) + open_(x, y + 1)
    tone = 2 if ul > dr else 0 if dr > ul else 1
    wrap = GRIPS[grip](x - y, x + y)
    return ('UVW' if wrap else 'uvw')[tone]


def roles(template, grip):
    """The template with every auto role resolved to a palette character."""
    assert len(template) == 16 and all(len(r) == 16 for r in template), 'templates are 16 rows of 16 characters'
    out = [list(r) for r in template]
    for y, row in enumerate(template):
        for x, ch in enumerate(row):
            if ch == '#':
                out[y][x] = str(_tone(template, x, y))
            elif ch == '%':
                out[y][x] = TRIM_TONE[_tone(template, x, y)]
            elif ch == 'H':
                out[y][x] = _handle(template, x, y, grip)
            elif ch == '@':
                out[y][x] = 'S'
    return out


def paint(grid, palette):
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    px = im.load()
    for y, row in enumerate(grid):
        for x, ch in enumerate(row):
            if ch != '.':
                px[x, y] = hexrgb(palette[ch]) + (255,)
    return im


def anchors(template):
    return sorted(((x, y) for y, row in enumerate(template) for x, ch in enumerate(row) if ch == '@'),
                  key=lambda p: (p[1], p[0]))


def line(a, b):
    """Bresenham pixels from a to b inclusive."""
    (x0, y0), (x1, y1) = a, b
    dx, dy = abs(x1 - x0), -abs(y1 - y0)
    sx, sy = (1 if x1 > x0 else -1), (1 if y1 > y0 else -1)
    err, pts = dx + dy, []
    while True:
        pts.append((x0, y0))
        if (x0, y0) == (x1, y1):
            return pts
        e2 = 2 * err
        if e2 >= dy:
            err, x0 = err + dy, x0 + sx
        if e2 <= dx:
            err, y0 = err + dx, y0 + sy


def under(grid, pts, ch):
    """Draw ch on transparent pixels only (a string passes behind the limbs / stock)."""
    for x, y in pts:
        if 0 <= x < 16 and 0 <= y < 16 and grid[y][x] == '.':
            grid[y][x] = ch


def over(grid, pixels):
    for (x, y), ch in pixels:
        if 0 <= x < 16 and 0 <= y < 16:
            grid[y][x] = ch


def arrow(tip, nock, shaft='B'):
    """An arrow along the x = y diagonal: 3-pixel head at tip, shaft, two pairs of fletching at the nock."""
    px = [((tip, tip), 'A'), ((tip + 1, tip), 'a'), ((tip, tip + 1), 'a')]
    px += [((k, k), shaft) for k in range(tip + 1, nock + 1)]
    px += [((nock - 1, nock), 'F'), ((nock, nock - 1), 'F'), ((nock - 2, nock - 1), 'f'), ((nock - 1, nock - 2), 'f')]
    return px


def rocket():
    """A firework rocket loaded along the stock: cone cap, banded paper tube, stick."""
    px = [((1, 1), 'A'), ((2, 1), 'a'), ((1, 2), 'a')]
    for k in range(2, 7):
        band = 'Q' if k == 4 else None
        px += [((k, k), band or 'R'), ((k + 1, k), band or 'r'), ((k, k + 1), band or 'O')]
    px += [((k, k), 'B') for k in range(7, 12)]
    return px


BOW_NOCK = {'bow': None, 'bow_pulling_0': 9, 'bow_pulling_1': 10, 'bow_pulling_2': 11}
CROSSBOW_NUT = {'crossbow_standby': None, 'crossbow_pulling_0': 9, 'crossbow_pulling_1': 11,
                'crossbow_pulling_2': 12, 'crossbow_arrow': 12, 'crossbow_firework': 12}


def textures(spec):
    """{state: 16x16 RGBA image} for one set: the 19 textures of check.TOOLSET_TEXTURES."""
    grip, palette = spec['grip'], dict(spec['palette'])
    palette.setdefault('R', '#D23A3A')
    palette.setdefault('r', '#FF7A6E')
    palette.setdefault('O', '#7A1620')
    palette.setdefault('Q', '#FFF1D0')
    out = {}
    for tool in ('sword', 'pickaxe', 'axe', 'shovel', 'hoe') + NEW_STATES:
        out[tool] = paint(roles(spec[tool], grip), palette)
    rod = spec['rod']
    (tip,) = anchors(rod)
    out['fishing_rod_cast'] = paint(roles(rod, grip), palette)
    g = roles(rod, grip)
    lure = [(tip[0], 13), (tip[0], 14), (tip[0] - 1, 14), (tip[0] - 1, 13)]
    under(g, [(tip[0], y) for y in range(tip[1] + 1, 13)], 'S')
    over(g, list(zip(lure, 'yzxy')))
    out['fishing_rod'] = paint(g, palette)
    top, bottom = anchors(spec['bow'])
    for state, nock in BOW_NOCK.items():
        g = roles(spec['bow'], grip)
        if nock is None:
            under(g, line(top, bottom), 'S')
        else:
            under(g, line(top, (nock, nock)) + line(bottom, (nock, nock)), 'S')
            over(g, arrow(nock - 8, nock))
        out[state] = paint(g, palette)
    top, bottom = anchors(spec['crossbow'])
    for state, nut in CROSSBOW_NUT.items():
        g = roles(spec['crossbow'], grip)
        if nut is None:
            under(g, line(top, bottom), 'S')
        else:
            under(g, line(top, (nut, nut)) + line(bottom, (nut, nut)), 'S')
        if state == 'crossbow_arrow':
            over(g, arrow(1, nut - 1, 'F'))
        elif state == 'crossbow_firework':
            over(g, rocket())
        out[state] = paint(g, palette)
    return out



