HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
PACK = os.path.join(ROOT, 'pack')
SPEC = os.path.join(HERE, 'spec.json')
EXPORT = os.path.join(HERE, 'export')
FIGMA = os.path.join(HERE, 'figma')
FIGMA_OUT = os.path.join(FIGMA, 'out')
DM_OUT = os.path.join(HERE, 'deluxemenus')
MOD_OUT = os.path.join(HERE, 'mod')
KEY = (229, 229, 229)
CMD = 7300  # custom_model_data of the invisible button item
SHIFT_IN, SHIFT_OUT = '\uE3F0', '\uE3F1'  # advances -8 and -169
GLYPH_MIN, GLYPH_MAX = 0xE300, 0xE3EF
REF = 'origins:menus'
WIDTH, CELL, GRID_X, GRID_Y = 176, 18, 7, 17
FIGMA_MAX = 50000  # use_figma code size limit, in characters
CHAMFER = {(0, 0), (1, 0), (0, 1), (173, 0), (174, 0), (175, 0), (174, 1), (175, 1), (175, 2)}
CLICKABLE = {'card', 'button', 'icon_button', 'tab', 'slot'}  # types that may carry an "item"
SOLID_CLICK = {'card', 'button', 'icon_button', 'tab'}  # drawn buttons (holes may not sit under them)
ACTIONS = {'click': 'click_commands', 'left': 'left_click_commands', 'right': 'right_click_commands',
           'shift_left': 'shift_left_click_commands', 'shift_right': 'shift_right_click_commands'}
# tuples, not sets: spec values may be unhashable and `in` must not raise on them
TYPES = ('panel', 'card', 'button', 'icon_button', 'tab', 'slot', 'text')
PANEL_STYLES = ('well', 'night', 'stripes')
CARD_COLORS = ('navy', 'red', 'green', 'gold', 'violet')
BTN_COLORS = ('red', 'green', 'gold', 'navy', 'done')
TAB_ICONS = ('left', 'right', 'up', 'down')
TEXT_COLORS = ('cream', 'gold')
LABEL_MAX = {2: 4, 3: 7, 4: 10}  # button width in cells -> max label characters
# a typo such as "shift_rigth" must fail validation instead of silently dropping the action
ELEMENT_KEYS = {'type', 'x', 'y', 'w', 'h', 'style', 'color', 'icon', 'label', 'item'}
ITEM_KEYS = {'key', 'name', 'lore', 'material', *ACTIONS}
MENU_KEYS = {'id', 'glyph', 'rows', 'title', 'open_command', 'elements', 'dynamic', 'renderer'}
SPEC_KEYS = {'menus', 'commands'}
COMMAND_KEYS = {'id', 'command', 'actions'}
DYNAMIC_KEYS = {'source', 'grid', 'prev', 'next'}
OPEN_MENU = '[openguimenu] '
MOD = 'mod'  # the only non-default value of a menu's "renderer"
ID_RE = re.compile(r'[a-z][a-z0-9_]*')
CMD_RE = re.compile(r'[a-z0-9_]+')
MAT_RE = re.compile(r'[A-Z0-9_]+')
GLYPH_RE = re.compile(r'[0-9A-Fa-f]{4}')
HEADER = '# Generated by menus/build.py from menus/spec.json. Do not edit; edit spec.json and rebuild.\n'


def rel(path):
    try:
        return os.path.relpath(path, ROOT).replace(os.sep, '/')
    except ValueError:  # path on another drive (Windows)
        return path


def write_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(data, f, indent=2)  # ensure_ascii default: chars stay as \uE3xx escapes
        f.write('\n')


def write_text(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def height(rows):
    return 17 + 18 * rows


def cells(e):
    x, y, w, h = e['x'], e['y'], e.get('w', 1), e.get('h', 1)
    return [(c, r) for r in range(y, y + h) for c in range(x, x + w)]


def slots(e):
    return sorted(r * 9 + c for c, r in cells(e))


def _int(v):
    return isinstance(v, int) and not isinstance(v, bool)


def _strs(v):
    return isinstance(v, list) and all(isinstance(s, str) for s in v)


def _is_mod(m):
    return m.get('renderer') == MOD


def _check_elements(m, ids, mods):
    mid, rows = m['id'], m['rows']
    mod = mid in mods
    els = m.get('elements')
    if not isinstance(els, list):
        raise SystemExit(f'{mid}: elements must be a list')

    def need(i, ok, msg):
        if not ok:
            raise SystemExit(f'{mid}: element {i} {msg}')

    keys = set()
    for i, e in enumerate(els):
        need(i, isinstance(e, dict), 'must be an object')
        need(i, not set(e) - ELEMENT_KEYS, f'has unknown keys {sorted(set(e) - ELEMENT_KEYS)}')
        t = e.get('type')
        need(i, t in TYPES, f'has unknown type {t!r}')
        x, y, w, h = e.get('x'), e.get('y'), e.get('w', 1), e.get('h', 1)
        for name, v in (('x', x), ('y', y), ('w', w), ('h', h)):
            need(i, _int(v), f'{name} must be an int')
        need(i, x >= 0 and y >= 0, 'x and y must be >= 0')
        need(i, w >= 1 and h >= 1, 'w and h must be >= 1')
        need(i, x + w <= 9, f'x + w = {x + w} > 9')
        need(i, y + h <= rows, f'y + h = {y + h} > rows {rows}')
        if t == 'panel':
            need(i, e.get('style') in PANEL_STYLES, f'style must be one of {PANEL_STYLES}')
        elif t == 'card':
            need(i, e.get('color') in CARD_COLORS, f'color must be one of {CARD_COLORS}')
            for k in ('icon', 'label'):
                need(i, k not in e or isinstance(e[k], str), f'{k} must be a string')
        elif t == 'button':
            need(i, e.get('color') in BTN_COLORS, f'color must be one of {BTN_COLORS}')
            label = e.get('label')
            need(i, isinstance(label, str) and label, 'label is required')
            need(i, h == 1, 'h must be 1')
            need(i, w in LABEL_MAX, f'w must be one of {tuple(LABEL_MAX)}')
            need(i, len(label) <= LABEL_MAX[w], f'label too long ({len(label)} > {LABEL_MAX[w]} for w={w})')
        elif t == 'icon_button':
            need(i, e.get('color') in BTN_COLORS, f'color must be one of {BTN_COLORS}')
            need(i, isinstance(e.get('icon'), str) and e['icon'], 'icon is required')
            need(i, w == 1 and h == 1, 'w and h must be 1')
        elif t == 'tab':
            need(i, e.get('color') in BTN_COLORS, f'color must be one of {BTN_COLORS}')
            need(i, e.get('icon') in TAB_ICONS, f'icon must be one of {TAB_ICONS}')
            need(i, w == 1 and h >= 2, 'w must be 1 and h >= 2')
        elif t == 'text':
            need(i, isinstance(e.get('label'), str) and e['label'], 'label is required')
            need(i, e.get('color') in TEXT_COLORS, f'color must be one of {TEXT_COLORS}')
            need(i, h == 1, 'h must be 1')
        if 'item' not in e:
            continue
        need(i, t in CLICKABLE, f'type {t} cannot carry an item')
        it = e['item']
        need(i, isinstance(it, dict), 'item must be an object')
        need(i, not set(it) - ITEM_KEYS, f'item has unknown keys {sorted(set(it) - ITEM_KEYS)}')
        k = it.get('key')
        need(i, isinstance(k, str) and ID_RE.fullmatch(k), 'item key must match [a-z][a-z0-9_]*')
        need(i, k not in keys, f'duplicate item key {k!r}')
        keys.add(k)
        if mod:  # the mod owns names, lore, materials and clicks; the spec only places the key
            need(i, set(it) == {'key'}, f'item of a mod menu must only have "key", found {sorted(set(it) - {"key"})}')
            continue
        need(i, isinstance(it.get('name'), str) and it['name'], 'item name is required')
        need(i, 'lore' not in it or _strs(it['lore']), 'item lore must be a list of strings')
        if t == 'slot':
            mat = it.get('material')
            need(i, isinstance(mat, str) and MAT_RE.fullmatch(mat), 'slot item needs a material matching [A-Z0-9_]+')
        else:
            need(i, 'material' not in it, f'item material is only allowed on slot items, not {t}')
        for a in ACTIONS:
            need(i, a not in it or _strs(it[a]), f'item {a} must be a list of strings')
            for cmd in it.get(a, []):
                target = cmd[len(OPEN_MENU):].strip() if cmd.startswith(OPEN_MENU) else None
                need(i, target is None or target in ids, f'{cmd!r} opens a menu that is not in the spec')
                need(i, target not in mods, f'{cmd!r} opens a mod menu, which DeluxeMenus cannot open')
        need(i, 'click' not in it or not any(a in it for a in ('left', 'right', 'shift_left', 'shift_right')),
             'item click cannot be combined with left/right/shift_left/shift_right')
    if m.get('dynamic'):
        reserved = re.compile(r'warp_\d+|prev_page|next_page')
        for i, e in enumerate(els):
            k = e.get('item', {}).get('key', '')
            need(i, not reserved.fullmatch(k), f'item key {k!r} is reserved for menus/warps_sync.py')
    # rule 3: items never share a cell; a hole never sits under a drawn button
    items = [(i, set(cells(e))) for i, e in enumerate(els) if 'item' in e]
    for (_, a), (j, b) in itertools.combinations(items, 2):
        need(j, not a & b, 'item overlaps the item of an earlier element')
    solid = [(i, set(cells(e))) for i, e in enumerate(els) if e['type'] in SOLID_CLICK]
    for i, e in enumerate(els):
        if e['type'] == 'slot':
            for j, sc in solid:
                need(i, not set(cells(e)) & sc, f'slot hole sits under drawn element {j}')


def _check_dynamic(m):
    """The warps_sync contract: a grid of cells filled with items, plus prev/next buttons drawn without an item."""
    mid, rows, els = m['id'], m['rows'], m['elements']
    d = m['dynamic']

    def need(ok, msg):
        if not ok:
            raise SystemExit(f'{mid}: dynamic {msg}')

    def area(name, v, keys):
        need(isinstance(v, dict) and set(v) == keys, f'{name} must be an object with keys {sorted(keys)}')
        need(all(_int(v[k]) for k in keys), f'{name} values must be ints')
        w, h = v.get('w', 1), v.get('h', 1)
        need(v['x'] >= 0 and v['y'] >= 0 and w >= 1 and h >= 1, f'{name}: x and y must be >= 0, w and h >= 1')
        need(v['x'] + w <= 9 and v['y'] + h <= rows, f'{name} is outside the 9 x {rows} area')
        return set(cells(v))

    need(isinstance(d, dict) and set(d) == DYNAMIC_KEYS, f'must be an object with keys {sorted(DYNAMIC_KEYS)}')
    need(d['source'] == 'ftb_warps', 'source must be "ftb_warps"')
    grid = area('grid', d['grid'], {'x', 'y', 'w', 'h'})
    arrows = {name: area(name, d[name], {'x', 'y'}) for name in ('prev', 'next')}
    for i, e in enumerate(els):
        need('item' not in e or not grid & set(cells(e)), f'grid overlaps the item of element {i}')
    buttons = {(e['x'], e['y']) for e in els if e['type'] == 'icon_button' and 'item' not in e}
    for name, c in arrows.items():
        need(c <= buttons, f'{name} must be the cell of an icon_button element without an item')
        need(not grid & c, f'{name} must not lie inside the grid')
    need(d['prev'] != d['next'], 'prev and next must be different cells')


def _check_commands(spec, ids, mods):
    cmds = spec.get('commands', [])
    if not isinstance(cmds, list):
        raise SystemExit('spec: "commands" must be a list')
    taken = set(ids)  # menu ids and command ids share the gui_menus namespace
    used = {c for m in spec['menus'] for c in m.get('open_command', [])}
    for n, c in enumerate(cmds):
        cid = c.get('id') if isinstance(c, dict) else None
        label = cid if isinstance(cid, str) else f'commands[{n}]'
        if not isinstance(c, dict) or set(c) != COMMAND_KEYS:
            raise SystemExit(f'{label}: command must be an object with keys {sorted(COMMAND_KEYS)}')
        if not isinstance(cid, str) or not ID_RE.fullmatch(cid):
            raise SystemExit(f'{label}: id must match [a-z][a-z0-9_]*')
        if cid in taken:
            raise SystemExit(f'{cid}: duplicate id (menu or command)')
        taken.add(cid)
        name = c['command']
        if not isinstance(name, str) or not CMD_RE.fullmatch(name):
            raise SystemExit(f'{cid}: command must match [a-z0-9_]+')
        if name in used:
            raise SystemExit(f'{cid}: duplicate command /{name}')
        used.add(name)
        acts = c['actions']
        if not _strs(acts) or not acts:
            raise SystemExit(f'{cid}: actions must be a non-empty list of strings')
        for a in acts:
            if a.startswith(OPEN_MENU) and a[len(OPEN_MENU):].strip() not in ids:
                raise SystemExit(f'{cid}: {a!r} opens a menu that is not in the spec')
            if a.startswith(OPEN_MENU) and a[len(OPEN_MENU):].strip() in mods:
                raise SystemExit(f'{cid}: {a!r} opens a mod menu, which DeluxeMenus cannot open')


def validate(spec):
    menus = spec.get('menus') if isinstance(spec, dict) else None
    if not isinstance(menus, list) or not menus:
        raise SystemExit('spec: "menus" must be a non-empty list')
    if set(spec) - SPEC_KEYS:
        raise SystemExit(f'spec: unknown keys {sorted(set(spec) - SPEC_KEYS)}')
    ids, glyphs = set(), set()
    for n, m in enumerate(menus):
        mid = m.get('id') if isinstance(m, dict) else None
        if not isinstance(mid, str) or not ID_RE.fullmatch(mid):
            raise SystemExit(f'menus[{n}]: id must match [a-z][a-z0-9_]*')
        if mid in ids:
            raise SystemExit(f'{mid}: duplicate menu id')
        if set(m) - MENU_KEYS:
            raise SystemExit(f'{mid}: unknown keys {sorted(set(m) - MENU_KEYS)}')
        ids.add(mid)
        g = m.get('glyph')
        if not isinstance(g, str) or not GLYPH_RE.fullmatch(g):
            raise SystemExit(f'{mid}: glyph must be 4 hex digits')
        cp = int(g, 16)
        if not GLYPH_MIN <= cp <= GLYPH_MAX:
            raise SystemExit(f'{mid}: glyph {g} outside U+{GLYPH_MIN:04X}..U+{GLYPH_MAX:04X}')
        if cp in glyphs:
            raise SystemExit(f'{mid}: duplicate glyph {g}')
        glyphs.add(cp)
        if not _int(m.get('rows')) or not 1 <= m['rows'] <= 6:
            raise SystemExit(f'{mid}: rows must be an int 1..6')
        if not isinstance(m.get('title'), str) or not m['title']:
            raise SystemExit(f'{mid}: title must be a non-empty string')
        oc = m.get('open_command')
        if oc is not None and not (isinstance(oc, list) and oc and all(isinstance(c, str) and CMD_RE.fullmatch(c)
                                                                         for c in oc)):
            raise SystemExit(f'{mid}: open_command must be a non-empty list of [a-z0-9_]+ strings')
        if 'renderer' in m and m['renderer'] != MOD:
            raise SystemExit(f'{mid}: renderer must be "{MOD}" or absent')
        if _is_mod(m):
            for k in ('open_command', 'dynamic'):
                if k in m:
                    raise SystemExit(f'{mid}: a mod menu cannot have {k}')
    mods = {m['id'] for m in menus if _is_mod(m)}
    dyn = [m['id'] for m in menus if 'dynamic' in m]
    if len(dyn) > 1:
        raise SystemExit(f'spec: only one menu may have "dynamic", found {dyn}')
    for m in menus:
        _check_elements(m, ids, mods)
        if 'dynamic' in m:
            _check_dynamic(m)
    _check_commands(spec, ids, mods)
    # warps_sync.py names extra pages <id>_2, <id>_3, ... and removes stale ones from config.yml
    for d in dyn:
        page = re.compile(re.escape(d) + r'_\d+')
        taken = [i for i in [m['id'] for m in menus] + [c['id'] for c in spec.get('commands', [])] if page.fullmatch(i)]
        if taken:
            raise SystemExit(f'spec: ids {taken} are reserved for the pages of dynamic menu {d!r}')


def expected_transparent(menu):
    out = set(CHAMFER)
    for e in menu['elements']:
        if e['type'] == 'slot':
            for c, r in cells(e):
                x0, y0 = GRID_X + 1 + CELL * c, GRID_Y + 1 + CELL * r  # 16x16 hole inside the 18x18 cell
                out.update((px, py) for px in range(x0, x0 + CELL - 2) for py in range(y0, y0 + CELL - 2))
    return out


def load_export(path, menu):
    name = rel(path)
    if not os.path.isfile(path):
        raise SystemExit(f'missing export {name}: export page-level frame '
                         f'{os.path.splitext(os.path.basename(path))[0]} from Figma (download_assets, png, scale 1)')
    try:
        with Image.open(path) as src:
            im = src.convert('RGBA')
    except (OSError, ValueError) as e:
        raise SystemExit(f'{name}: cannot read PNG: {e}')
    want = (WIDTH, height(menu['rows']))
    if im.size != want:
        raise SystemExit(f'{name}: size {im.width}x{im.height}, expected {want[0]}x{want[1]} (export at scale 1)')
    px = im.load()
    for y in range(im.height):
        for x in range(im.width):
            if px[x, y][:3] == KEY:
                px[x, y] = (0, 0, 0, 0)
    alphas = set(im.getchannel('A').tobytes())
    if not alphas <= {0, 255}:
        raise SystemExit(f'{name}: non-binary alpha {sorted(alphas - {0, 255})}')
    clear = {(x, y) for y in range(im.height) for x in range(im.width) if px[x, y][3] == 0}
    expect = expected_transparent(menu)
    extra = sorted(clear - expect, key=lambda c: (c[1], c[0]))
    missing = sorted(expect - clear, key=lambda c: (c[1], c[0]))
    if extra or missing:
        raise SystemExit(f'{name}: {len(extra)} pixels unexpectedly transparent (first 5 {extra[:5]}), '
                         f'{len(missing)} pixels unexpectedly opaque (first 5 {missing[:5]})')
    return im


def yaml_menu(menu):
    doc = {'menu_title': '&f' + SHIFT_IN + chr(int(menu['glyph'], 16)) + SHIFT_OUT + '&#fff1d0' + menu['title']}
    if 'open_command' in menu:
        doc['open_command'] = list(menu['open_command'])
    doc['size'] = menu['rows'] * 9
    items = {}
    for e in menu['elements']:
        it = e.get('item')
        if it is None:
            continue
        d = {'material': it['material']} if 'material' in it else {'material': 'PAPER', 'model_data': CMD}
        d['slots'] = slots(e)
        d['display_name'] = it['name']
        if 'lore' in it:
            d['lore'] = list(it['lore'])
        for a, key in ACTIONS.items():
            if a in it:
                d[key] = list(it[a])
        items[it['key']] = d
    doc['items'] = items
    return doc


def command_doc(cmd: dict) -> dict:
    # DeluxeMenus skips menus without a title or items, so both are present. The always-false open requirement means
    # the menu never opens and its deny_commands run as the command's actions.
    return {'menu_title': cmd['id'], 'open_command': [cmd['command']], 'register_command': True, 'size': 9,
            'open_requirement': {'requirements': {'never': {'type': 'string equals', 'input': 'a', 'output': 'b'}},
                                 'deny_commands': list(cmd['actions'])},
            'items': {'placeholder': {'material': 'PAPER', 'model_data': CMD, 'slots': [0], 'display_name': ' '}}}


def dump_yaml(doc):
    # allow_unicode=False writes the private-use title characters as \uXXXX inside double quotes, which SnakeYAML
    # (DeluxeMenus) reads back
    text = HEADER + yaml.safe_dump(doc, allow_unicode=False, sort_keys=False, default_flow_style=False, width=1000)
    assert yaml.safe_load(text) == doc, 'yaml round-trip mismatch'
    return text


def load_spec(path):
    try:
        with open(path, encoding='utf-8') as f:
            spec = json.load(f)
    except (OSError, ValueError) as e:
        raise SystemExit(f'cannot read {rel(path)}: {e}')
    validate(spec)
    return spec


def _prune(folder, ext, keep):
    """Delete <stem><ext> files in folder whose stem is not in keep."""
    for name in os.listdir(folder):
        stem, e = os.path.splitext(name)
        if e == ext and stem not in keep:
            os.remove(os.path.join(folder, name))


def write_layouts(menus, mod_out=MOD_OUT):
    """Write mod_out/<id>.json for each mod menu, prune stale ones, and return the paths written."""
    os.makedirs(mod_out, exist_ok=True)
    mods = [m for m in menus if _is_mod(m)]
    paths = []
    for m in mods:
        path = os.path.join(mod_out, m['id'] + '.json')
        write_json(path, {'id': m['id'], 'rows': m['rows'], 'glyph': m['glyph'],
                          'slots': {e['item']['key']: slots(e) for e in m['elements'] if 'item' in e}})
        paths.append(path)
    _prune(mod_out, '.json', {m['id'] for m in mods})
    return paths


def layouts(spec_path=SPEC, mod_out=MOD_OUT):
    for p in write_layouts(load_spec(spec_path)['menus'], mod_out):
        print(rel(p))


# Only what lib.js/menus.js draw from: item names, lore, clicks, glyphs and commands never reach Figma, and embedding
# them pushed menus.run.js past FIGMA_MAX.
FIGMA_MENU_KEYS = ('id', 'rows', 'title', 'open_command')
FIGMA_ELEMENT_KEYS = ('type', 'x', 'y', 'w', 'h', 'style', 'color', 'icon', 'label')


def figma_spec(spec):
    return {'menus': [
        {**{k: m[k] for k in FIGMA_MENU_KEYS if k in m},
         'elements': [{k: e[k] for k in FIGMA_ELEMENT_KEYS if k in e} for e in m['elements']]}
        for m in spec['menus']]}


def figma(spec_path=SPEC, figma_dir=FIGMA, out_dir=FIGMA_OUT):
    spec = load_spec(spec_path)
    src = {}
    for n in ('lib', 'kit', 'menus'):
        p = os.path.join(figma_dir, n + '.js')
        if not os.path.isfile(p):
            raise SystemExit(f'missing {rel(p)}')
        with open(p, encoding='utf-8') as f:
            src[n] = f.read()
    runs = {'kit.run.js': src['lib'] + '\n' + src['kit'],
            'menus.run.js': src['lib'] + '\nconst SPEC = ' + json.dumps(figma_spec(spec), separators=(',', ':')) + ';\n' + src['menus']}
    for name, text in runs.items():
        if len(text) > FIGMA_MAX:
            raise SystemExit(f'{name}: {len(text)} characters, limit {FIGMA_MAX}')
    for name, text in runs.items():
        p = os.path.join(out_dir, name)
        write_text(p, text)
        print(f'{rel(p)} {len(text)} chars')


def build(spec_path=SPEC, export_dir=EXPORT, pack=PACK, dm_out=DM_OUT, mod_out=MOD_OUT):
    spec = load_spec(spec_path)
    menus = spec['menus']
    # load every export before writing anything, so a bad export leaves the outputs untouched
    ims = [load_export(os.path.join(export_dir, f'menu_{m["id"]}.png'), m) for m in menus]
    written = []

    def jw(path, data):
        write_json(path, data)
        written.append(path)

    def tw(path, text):
        write_text(path, text)
        written.append(path)

    def png(im, path):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        im.save(path)
        written.append(path)

    tex = os.path.join(pack, 'assets', 'origins', 'textures', 'menu')
    for m, im in zip(menus, ims):
        png(im, os.path.join(tex, m['id'] + '.png'))
    _prune(tex, '.png', {m['id'] for m in menus})

    providers = [{'type': 'space', 'advances': {SHIFT_IN: -8, SHIFT_OUT: -169}}]
    for m in menus:
        providers.append({'type': 'bitmap', 'file': f'origins:menu/{m["id"]}.png', 'ascent': 13,
                          'height': height(m['rows']), 'chars': [chr(int(m['glyph'], 16))]})
    jw(os.path.join(pack, 'assets', 'origins', 'font', 'menus.json'), {'providers': providers})

    default = os.path.join(pack, 'assets', 'minecraft', 'font', 'default.json')
    data = {'providers': []}
    if os.path.exists(default):
        with open(default, encoding='utf-8') as f:
            data = json.load(f)
    if not any(p.get('type') == 'reference' and p.get('id') == REF for p in data['providers']):
        data['providers'].append({'type': 'reference', 'id': REF})
    jw(default, data)

    jw(os.path.join(pack, 'assets', 'minecraft', 'models', 'item', 'paper.json'),
       {'parent': 'minecraft:item/generated', 'textures': {'layer0': 'minecraft:item/paper'},
        # the predicate matches custom_model_data >= value and the last matching override wins, so 7301 hands every
        # higher value back to plain paper: only exactly 7300 is invisible
        'overrides': [{'predicate': {'custom_model_data': CMD}, 'model': 'origins:item/menu_blank'},
                      {'predicate': {'custom_model_data': CMD + 1}, 'model': 'origins:item/paper_plain'}]})
    jw(os.path.join(pack, 'assets', 'origins', 'models', 'item', 'paper_plain.json'),
       {'parent': 'minecraft:item/generated', 'textures': {'layer0': 'minecraft:item/paper'}})
    jw(os.path.join(pack, 'assets', 'origins', 'models', 'item', 'menu_blank.json'),
       {'parent': 'minecraft:item/generated', 'textures': {'layer0': 'origins:item/menu_blank'}})
    png(Image.new('RGBA', (16, 16), (0, 0, 0, 0)),
        os.path.join(pack, 'assets', 'origins', 'textures', 'item', 'menu_blank.png'))

    cmds = spec.get('commands', [])
    dm = [m for m in menus if not _is_mod(m)]  # mod menus are opened by the mod, DeluxeMenus never sees them
    for m in dm:
        tw(os.path.join(dm_out, m['id'] + '.yml'), dump_yaml(yaml_menu(m)))
    for c in cmds:
        tw(os.path.join(dm_out, c['id'] + '.yml'), dump_yaml(command_doc(c)))
    tw(os.path.join(dm_out, 'gui_menus.yml'),
       dump_yaml({'gui_menus': {x['id']: {'file': x['id'] + '.yml'} for x in dm + cmds}}))
    _prune(dm_out, '.yml', {x['id'] for x in dm + cmds} | {'gui_menus'})
    written.extend(write_layouts(menus, mod_out))

    for m in menus:
        n = sum('item' in e for e in m['elements'])
        print(f'{m["id"]} U+{int(m["glyph"], 16):04X} rows={m["rows"]} size={WIDTH}x{height(m["rows"])} items={n}')
    print(f'{len(written)} files written')


def report(spec_path=SPEC):
    spec = load_spec(spec_path)
    for m in spec['menus']:
        print(f'ok {m["id"]} rows={m["rows"]} items={sum("item" in e for e in m["elements"])}')
    for c in spec.get('commands', []):
        print(f'ok command {c["id"]} /{c["command"]}')


def _synthetic(menu):
    """A valid export for menu: opaque navy with the page-background key on every pixel that must be transparent."""
    im = Image.new('RGBA', (WIDTH, height(menu['rows'])), (10, 16, 36, 255))
    px = im.load()
    for xy in expected_transparent(menu):
        px[xy] = KEY + (255,)
    return im


def _rejects(fn, word):
    try:
        fn()
    except SystemExit as e:
        assert word in str(e.code), f'expected {word!r} in {e.code!r}'
        return
    raise AssertionError(f'expected SystemExit containing {word!r}')


def _load(path):
    with open(path, encoding='utf-8') as f:
        return json.load(f)


def _check_rejects(check, pack):
    """check.py must fail (AssertionError) on each broken copy of a valid pack."""
    fonts = os.path.join(pack, 'assets', 'origins', 'font')
    good = _load(os.path.join(fonts, 'menus.json'))

    def broken(mutate, word, prefixes=None):
        bad = json.loads(json.dumps(good))
        mutate(bad['providers'])
        with tempfile.TemporaryDirectory() as tmp:
            copy = os.path.join(tmp, 'pack')
            shutil.copytree(pack, copy)
            write_json(os.path.join(copy, 'assets', 'origins', 'font', 'menus.json'), bad)
            if prefixes:
                write_json(os.path.join(copy, 'assets', 'origins', 'font', 'prefixes.json'), prefixes)
            try:
                with contextlib.redirect_stdout(io.StringIO()):
                    check.check(copy)
            except AssertionError as e:
                assert word in str(e), f'expected {word!r} in {e}'
                return
            raise AssertionError(f'check.py accepted a pack with {word}')

    broken(lambda p: p[1].update(height=p[1]['height'] + 1), 'cell height')
    broken(lambda p: p[1].update(ascent=p[1]['height'] + 1), 'ascent')
    broken(lambda p: p[0]['advances'].update({p[1]['chars'][0]: -1}), 'already used')
    broken(lambda p: p[0]['advances'].update({'': -1}), 'already used',
           prefixes={'providers': [{'type': 'space', 'advances': {'': 1}}]})


